"""Pack scratch lifetimes delimited only by unconditional R/HMR resets.

This independently implemented pass changes physical scratch labels, never gate
order, phase angles, measurement bits, or input labels. Conditional resets do
not terminate a lifetime. A wire without a final unconditional reset stays live
through EOF. Thus reuse needs no sampled claim that a wire happens to be zero.
The source circuit's license and ancestry remain applicable to generated bytes.
"""
from __future__ import annotations

import argparse
from collections import Counter
from datetime import datetime, timezone
import heapq
import json
from pathlib import Path
import re
import sys
import time

Q = re.compile(r'\bq(\d+)\b')
ALLOWED = {'APPEND_TO_REGISTER', 'REGISTER', 'R', 'HMR', 'X', 'CX', 'CCX',
           'Z', 'CZ', 'CCZ', 'Z_POW', 'SWAP', 'CSWAP', 'NEG', 'BIT_INVERT',
           'BIT_STORE0', 'BIT_STORE1', 'PUSH_CONDITION', 'POP_CONDITION'}


def pack(text):
    lines = text.splitlines()
    fixed = set()
    # Registers are fixed throughout, including any declarations after first use.
    for line in lines:
        if line.startswith('APPEND_TO_REGISTER '):
            fixed.update(map(int, Q.findall(line)))
    if fixed != set(range(22)):
        raise ValueError('Expected exactly the 22 fixed InvSqrt input qubits')
    intervals, active, line_intervals = [], {}, []
    depth = 0
    conditional_resets = 0
    original = set(fixed)
    for index, line in enumerate(lines):
        fields = line.split()
        op = fields[0] if fields else None
        if op is not None and op not in ALLOWED:
            raise ValueError(f'Unsupported operation {op}')
        qubits = set(map(int, Q.findall(line))) if op != 'REGISTER' else set()
        original.update(qubits)
        uses = {}
        for q in sorted(qubits - fixed):
            if q not in active:
                active[q] = len(intervals)
                intervals.append({'logical': q, 'start': index, 'end': len(lines),
                                  'ends_in_reset': False})
            uses[q] = active[q]
        line_intervals.append(uses)
        if op in ('R', 'HMR'):
            if len(qubits) != 1:
                raise ValueError('Expected one reset target')
            if depth == 0 and 'if' not in fields:
                for q in qubits - fixed:
                    interval = intervals[active.pop(q)]
                    interval.update(end=index, ends_in_reset=True)
            else:
                conditional_resets += 1
        if op == 'PUSH_CONDITION':
            # Quantum controls spanning a block need a separate lifetime proof.
            if qubits:
                raise ValueError('Only classical PUSH_CONDITION is supported')
            depth += 1
        elif op == 'POP_CONDITION':
            depth -= 1
            if depth < 0:
                raise ValueError('Unbalanced conditions')
    if depth:
        raise ValueError('Unbalanced conditions')
    free, busy, width, peak = [], [], 22, 0
    peak_ids = []
    for k, interval in enumerate(intervals):
        while busy and busy[0][0] < interval['start']:
            _, physical, _ = heapq.heappop(busy)
            heapq.heappush(free, physical)
        if free:
            physical = heapq.heappop(free)
        else:
            physical = width
            width += 1
        interval['physical'] = physical
        heapq.heappush(busy, (interval['end'], physical, k))
        if len(busy) > peak:
            peak = len(busy)
            peak_ids = [i for _, _, i in busy]
    result = []
    for line, uses in zip(lines, line_intervals):
        if line.startswith('REGISTER '):
            result.append(line)
            continue
        def replace(match):
            q = int(match[1])
            return f"q{q if q in fixed else intervals[uses[q]]['physical']}"
        result.append(Q.sub(replace, line))
    return '\n'.join(result) + '\n', {
        'original_qubits': max(original) + 1, 'packed_qubits': width,
        'scratch_interval_peak': peak, 'interval_count': len(intervals),
        'conditional_resets_not_released': conditional_resets,
        'unterminated_intervals': len(active), 'peak_interval_ids': peak_ids,
        'intervals': intervals,
        'operations': dict(Counter(line.split()[0] for line in lines if line.strip())),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--parent-output', type=Path, required=True)
    ap.add_argument('--output-dir', type=Path, required=True)
    args = ap.parse_args()
    from generate import ROOT, output_workspace, sha256
    sys.path.insert(0, str(ROOT / 'kickmix'))
    import kickmix as km
    start = time.monotonic()
    parent = args.parent_output / 'invsqrt.kmb'
    candidate = args.output_dir.resolve().parent
    screen = candidate / 'screen'
    screen.mkdir(exist_ok=True)
    source = km.Circuit.from_file(parent)
    source.to_file(screen / 'parent.kmx')
    result, analysis = pack((screen / 'parent.kmx').read_text())
    (screen / 'lifetimes.json').write_text(json.dumps(analysis, indent=2)+'\n')
    (screen / 'packed.kmx').write_text(result)
    packed = km.Circuit.from_file(screen / 'packed.kmx')
    if dict(source.operation_statistics()) != dict(packed.operation_statistics()):
        raise AssertionError('Renaming unexpectedly changed operation statistics')
    if packed.num_qubits != analysis['packed_qubits']:
        raise AssertionError('Resource estimate differs from parsed circuit')
    with output_workspace(args.output_dir) as (output, stage):
        packed.to_file(stage / 'invsqrt.kmb')
    report = {'kind':'unconditional_reset_lifetime_packing',
              'official_validation':False, 'created_at':datetime.now(timezone.utc).isoformat(),
              'parent_output':str(args.parent_output.resolve()),
              'parent_sha256':sha256(parent), 'generator_sha256':sha256(Path(__file__)),
              'python_executable':sys.executable, 'python_prefix':sys.prefix,
              'elapsed_seconds':time.monotonic()-start,
              'screen':{k:v for k,v in analysis.items() if k!='intervals'},
              'artifacts':[{'path':'invsqrt.kmb','sha256':sha256(output/'invsqrt.kmb')}],
              'decision':'plausible_width_gain' if packed.num_qubits < source.num_qubits else 'screened_out_no_width_gain'}
    (candidate/'generation.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))


if __name__ == '__main__':
    main()
